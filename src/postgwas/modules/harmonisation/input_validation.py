"""Three-stage validation of a GWAS harmonisation configuration.

Plan v3 Part 2.  Validation is split into three stages so that a mistyped
column name costs a second rather than a full parse of a ten-million-row file:

    stage 1  validate_config(cfg, policies)                 config only, no file read
    stage 2  validate_header(cfg, sumstat_path, policies)   reads one line
    stage 3  validate_content(cfg, df, policies)            needs the parsed data

Every stage returns ``(is_valid, problems)`` and every stage collects **all**
problems; none stops at the first.  Each problem is a :class:`Problem` record
carrying ``config_key``, ``configured_value``, ``issue`` and ``suggestion``, so
the error message is generated by :func:`format_problems` rather than
hand-written per case.

"""

