# Report generation — the message is generated, not hand-written
# ======================================================================
def format_problems(
    problems,
    title=None,
    columns_present=None,
    source_name=None,
    footer=None,
):
    # type: (Sequence[Problem], Optional[str], Optional[Sequence[str]], Optional[str], Optional[str]) -> str
    """Render a list of :class:`Problem` records as the plan 2.3 report."""
    problems = list(problems or [])
    if not problems:
        return ""

    errors = [p for p in problems if p.severity == "error"]
    count = len(errors) if errors else len(problems)
    noun = "problem" if count == 1 else "problems"
    lines = []
    if title:
        lines.append("%s - %d %s found." % (title, count, noun))
        lines.append("")

    # Sections in registry order, then anything unexpected, in first-seen order.
    order = [c for c in CATEGORY_HEADINGS if any(p.category == c for p in problems)]
    for problem in problems:
        if problem.category not in order:
            order.append(problem.category)

    for category in order:
        group = [p for p in problems if p.category == category]
        if not group:
            continue
        heading = CATEGORY_HEADINGS.get(category, "Other problems:")
        lines.append("  %s" % heading)
        lines.append("")
        key_width = max(len(p.config_key) for p in group)
        value_width = max(len(p.rendered_value()) for p in group)
        for problem in group:
            marker = "" if problem.severity == "error" else "(warning) "
            lines.append("    %s%s" % (marker, problem.line(key_width, value_width)))
        lines.append("")

    if columns_present:
        where = " in %s" % source_name if source_name else ""
        lines.append(
            "  Columns actually present%s (%d):" % (where, len(columns_present))
        )
        lines.append("    %s" % ", ".join(str(c) for c in columns_present))
        lines.append("")

    if footer:
        lines.append("  %s" % footer)

    return "\n".join(lines).rstrip() + "\n"


