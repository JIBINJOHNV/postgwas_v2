# required_inputs -- declarative, in config column names
# ---------------------------------------------------------------------------

def _resolve_virtual(cfg, token):
    """Resolve an '@name' alternative that is not a config column."""
    return False


def _alternative_text(alternative):
    """'chr_col + pos_col', or a plain key, or the prose for an '@' token."""
    return " + ".join(alternative)


def _check_required_inputs(cfg, requirements=None, policies=None):
    """Evaluate every required_inputs group against one config row."""
    groups = requirements
    if groups is None and policies is not None:
        groups = getattr(policies, "required_inputs", None)
    if groups is None:
        from .policies import REQUIRED_INPUTS as groups  # type: ignore
    problems = []
    for name in groups:
        spec = groups[name] or {}
        if not spec.get("required", True):
            continue
        alternatives = spec.get("any_of") or []
        satisfied = False
        for alternative in alternatives:
            ok = True
            for key in alternative:
                if key.startswith("@"):
                    if not _resolve_virtual(cfg, key):
                        ok = False
                        break
                elif not _is_set(cfg.get(key)):
                    ok = False
                    break
            if ok:
                satisfied = True
                break
        if satisfied:
            continue

        label = spec.get("label", name)
        options = "; or ".join(_alternative_text(a) for a in alternatives)
        # Show what the config currently says for each key involved, so the
        # user can see which one they left as NA.
        seen, current = [], []
        for alternative in alternatives:
            for key in alternative:
                if key.startswith("@") or key in seen:
                    continue
                seen.append(key)
                current.append("%s=%s" % (key, cfg.get(key, "(absent)")))
        problems.append(
            Problem(
                config_key=", ".join(seen) or name,
                configured_value=None,
                issue="no source of %s is configured" % label,
                suggestion=(
                    "Set %s. Currently: %s.%s"
                    % (options, ", ".join(current),
                       (" " + " ".join(str(spec["why"]).split()))
                       if spec.get("why") else "")
                ),
                category="missing_field",
                stage="config",
            )
        )
    return problems


def validate_config(cfg, policies=None, logger=None):
    # type: (Dict[str, Any], Any, Any) -> Tuple[bool, List[Problem]]
    """Stage 1 — everything that can be decided without opening the input file.

    Checks the mandatory config entries, the mandatory-with-alternatives rules
    for EAF / INFO / sample size, that every configured file exists and is not
    empty, that external files contain the column they are configured to
    supply, that scalar sample sizes are positive whole numbers, and that the
    policy block itself is valid.

    Returns ``(is_valid, problems)`` and never stops at the first problem.
    """
    problems = []  # type: List[Problem]
    policies = _resolve_policies(policies, problems)
    cfg = cfg or {}

    # ---- 1. what the dataset must supply ----------------------------
    #
    # Declared in the registry's `required_inputs:` block, in the CONFIG COLUMN
    # NAMES used in the config CSV.  A group is satisfied when every key of any
    # ONE alternative is set.  Nothing is read from disk yet: a config that
    # fails here is rejected before the sumstat file is opened.
    problems.extend(_check_required_inputs(cfg, policies=policies))

    # Reject NOW if any requirement is unmet.  Checking whether files exist or
    # whether columns are present is pointless -- and produces confusing
    # follow-on errors such as "eaffile does not exist" when eaffile is NA --
    # until the config names everything the pipeline needs.
    if problems:
        return False, problems

    # ---- 6. every configured file exists and is not empty -----------
    for key, human, required in FILE_CONFIG_KEYS:
        value = _clean(cfg.get(key))
        if not value:
            if required:
                continue  # already reported as a missing mandatory entry
            continue
        if not _looks_like_path(value):
            # A bare name such as 'EUR' is resolved later against the resource
            # folder by resolve_resource_file; it is not a path.
            continue
        _check_file(key, value, human, problems, required)

    resource_folder = _clean(cfg.get("resource_folder"))
    if resource_folder and not os.path.isdir(resource_folder):
        problems.append(
            Problem(
                config_key="resource_folder",
                configured_value=resource_folder,
                issue="is not an existing directory",
                suggestion="The reference resources are looked up under this folder.",
                category="file_missing",
                stage="config",
            )
        )

    # ---- 7. external files contain the column they supply -----------
    _check_external_column("eaffile", "eafcolumn", cfg, policies, problems)
    _check_external_column("infofile", "infocolumn", cfg, policies, problems)

    # ---- 8. scalar sample sizes -------------------------------------
    minimum = int(policies.get("sample_size.min_value"))
    for key in ("ncase", "ncontrol", "n", "total_n"):
        _positive_int(key, cfg.get(key), minimum, problems)

    # ---- 9. the output directory is usable --------------------------
    output_folder = _clean(cfg.get("output_folder"))
    if output_folder:
        probe = os.path.abspath(output_folder)
        existing = probe
        while existing and not os.path.exists(existing):
            parent = os.path.dirname(existing)
            if parent == existing:
                break
            existing = parent
        if not existing or not os.path.isdir(existing):
            problems.append(
                Problem(
                    config_key="output_folder",
                    configured_value=output_folder,
                    issue="cannot be created; no part of the path exists",
                    suggestion="Create the parent directory first.",
                    category="output",
                    stage="config",
                )
            )
        elif not os.access(existing, os.W_OK):
            problems.append(
                Problem(
                    config_key="output_folder",
                    configured_value=output_folder,
                    issue="is not writable (nearest existing directory is %s)" % existing,
                    suggestion="Results cannot be written there.",
                    category="output",
                    stage="config",
                )
            )

    valid = _ok(problems)
    if logger is not None:
        if valid:
            _emit(logger, "Configuration check passed; nothing has been read yet.")
        else:
            _emit(
                logger,
                format_problems(problems, title="Configuration check"),
                warn=True,
            )
    return valid, problems


# ======================================================================
# STAGE 2 — the header, and nothing but the header
# ======================================================================
def validate_header(cfg, sumstat_path, policies=None, logger=None):
    # type: (Dict[str, Any], str, Any, Any) -> Tuple[bool, List[Problem]]
    """Stage 2 — every configured column name is checked against the header.

    Reads one line.  Catches names that are absent, names that differ only in
    case or surrounding whitespace, near misses (with a suggestion), two config
    keys resolving to the same column, and a column name repeated in the file
    itself.
    """
    problems = []  # type: List[Problem]
    policies = _resolve_policies(policies, problems)
    cfg = cfg or {}

    path = _clean(sumstat_path) or _clean(cfg.get("sumstat_file"))
    if not path:
        problems.append(
            Problem(
                config_key="sumstat_file",
                configured_value=None,
                issue="no summary statistics file was given",
                suggestion="Nothing could be checked.",
                category="missing_key",
                stage="header",
            )
        )
        return False, problems
    if not os.path.exists(path):
        problems.append(
            Problem(
                config_key="sumstat_file",
                configured_value=path,
                issue="does not exist",
                suggestion="The header could not be read.",
                category="file_missing",
                stage="header",
            )
        )
        return False, problems

    declared_delimiter = _clean(cfg.get("delimiter"))
    if declared_delimiter and declared_delimiter.lower() != "auto":
        detected = detect_delimiter(
            path,
            candidates=list(policies.get("input.delimiter_candidates")),
            minimum_columns=int(policies.get("input.delimiter_min_columns")),
            maximum_columns=int(policies.get("input.delimiter_max_columns")),
            sample_lines=int(policies.get("input.delimiter_sample_rows")),
            comment_prefix=(
                "##" if bool(policies.get("input.strip_double_hash_lines")) else None
            ),
            fail_policy="unknown",
        )
        if (
            detected.kind == "delimiter"
            and detected.value != delimiter_character(declared_delimiter.lower())
        ):
            action = str(policies.get("validation.declaration_mismatch_action"))
            message = (
                "DECLARATION MISMATCH: sample sheet declares delimiter %r, but "
                "automatic detection found %r. Policy "
                "validation.declaration_mismatch_action=%r; the declared delimiter "
                "remains authoritative."
                % (declared_delimiter.lower(), detected.value, action)
            )
            emit_high_visibility_warning(logger, message)
            if action == "fail":
                problems.append(
                    Problem(
                        config_key="delimiter",
                        configured_value=declared_delimiter,
                        issue="disagrees with automatic delimiter detection",
                        suggestion=(
                            "Correct the sample-sheet delimiter, or set "
                            "validation.declaration_mismatch_action to 'warn' to "
                            "continue with the declaration."
                        ),
                        category="bad_value",
                        stage="header",
                    )
                )

    try:
        header, separator = read_summary_statistics_header(path, policies)
    except Exception as exc:
        problems.append(
            Problem(
                config_key="sumstat_file",
                configured_value=path,
                issue="header could not be read (%s)" % exc,
                suggestion="The file may be truncated, corrupt or compressed oddly.",
                category="file_unreadable",
                stage="header",
            )
        )
        return False, problems

    if not header:
        problems.append(
            Problem(
                config_key="sumstat_file",
                configured_value=path,
                issue="has no header line",
                suggestion="The file looks empty once '##' metadata is skipped.",
                category="file_unreadable",
                stage="header",
            )
        )
        return False, problems

    # ---- repeated column names in the file itself -------------------
    # Polars renames the second occurrence to NAME_duplicated_0, so the config
    # silently gets the first one.  (The current io.py detectors look for an
    # 'Unnamed:' prefix and a '_duplicated' *prefix*, both pandas conventions
    # that polars never produces; they can never fire.)
    duplicate_severity = _severity_for(policies.get("validation.on_duplicate_header"))
    for name, count in Counter(header).items():
        if count > 1:
            problems.append(
                Problem(
                    config_key="sumstat_file",
                    configured_value=None,
                    issue="the file has %d columns called '%s'" % (count, name),
                    suggestion=(
                        "Polars keeps the first and renames the rest to "
                        "'%s_duplicated_0', so a config naming '%s' silently gets the "
                        "first one." % (name, name)
                    ),
                    category="duplicate_header",
                    stage="header",
                    severity=duplicate_severity,
                    standalone=True,
                )
            )

    blank = [index for index, name in enumerate(header) if not name.strip()]
    if blank:
        problems.append(
            Problem(
                config_key="sumstat_file",
                configured_value=None,
                issue="the header has %d unnamed column(s) (position %s)"
                % (len(blank), ", ".join(str(i + 1) for i in blank)),
                suggestion="This usually means the delimiter was guessed wrongly.",
                category="duplicate_header",
                stage="header",
                severity="warning",
                standalone=True,
            )
        )

    # ---- one lookup table per matching rule -------------------------
    exact = set(header)
    loose = {}  # type: Dict[str, List[str]]
    for name in header:
        loose.setdefault(name.strip().lower(), []).append(name)

    cutoff = float(policies.get("validation.fuzzy_match_cutoff"))

    # chr_col / pos_col may legitimately be derived from a combined column.
    chr_pos = _clean(cfg.get("chr_pos_col"))
    derived_coordinates = bool(chr_pos) and chr_pos in exact

    by_value = OrderedDict()  # type: Dict[str, List[str]]
    for key in COLUMN_CONFIG_KEYS:
        value = _clean(cfg.get(key))
        if not value:
            continue  # a normalized missing value means this column was not supplied
        if derived_coordinates and key in ("chr_col", "pos_col"):
            continue
        by_value.setdefault(value, []).append(key)
        if value in exact:
            continue
        candidates = loose.get(value.strip().lower())
        if candidates:
            suggestion = "Did you mean '%s'?  (only the case or surrounding whitespace differs)" % (
                candidates[0],
            )
        else:
            close = difflib.get_close_matches(value, header, n=1, cutoff=cutoff)
            suggestion = (
                "Closest match in file: '%s'" % close[0]
                if close
                else "No similar column name."
            )
        problems.append(
            Problem(
                config_key=key,
                configured_value=value,
                issue="not found",
                suggestion=suggestion,
                category="column_not_found",
                stage="header",
            )
        )

    # ---- two config keys on one column ------------------------------
    ambiguous_severity = _severity_for(
        policies.get("validation.on_ambiguous_column_mapping")
    )
    for value, keys in by_value.items():
        if len(keys) < 2:
            continue
        joined = " and ".join(keys)
        problems.append(
            Problem(
                config_key=", ".join(keys),
                configured_value=None,
                issue="%s are both set to '%s'" % (joined, value),
                suggestion=(
                    "Reading the same column twice ends in a polars duplicate-name "
                    "error that names the column, not the config keys."
                ),
                category="ambiguous_mapping",
                stage="header",
                severity=ambiguous_severity,
                standalone=True,
            )
        )

    # ---- cross-check what polars will actually see ------------------
    effective = _polars_header(path, separator)
    if effective is not None and len(effective) != len(header):
        problems.append(
            Problem(
                config_key="input.delimiter",
                configured_value=repr(separator),
                issue=(
                    "splits the header into %d columns but polars reads %d"
                    % (len(header), len(effective))
                ),
                suggestion="Set input.delimiter explicitly if the guess is wrong.",
                category="file_unreadable",
                stage="header",
                severity="warning",
            )
        )

    valid = _ok(problems)
    if logger is not None:
        if valid:
            _emit(
                logger,
                "Header check passed: all %d configured column names are in the file."
                % len(by_value),
            )
        else:
            _emit(
                logger,
                format_problems(
                    problems,
                    title="Configuration check for %s"
                    % (_clean(cfg.get("gwas_outputname")) or os.path.basename(path)),
                    columns_present=header,
                    source_name=os.path.basename(path),
                    footer="Nothing was read beyond the header. Fix the config and re-run.",
                ),
                warn=True,
            )
    return valid, problems


