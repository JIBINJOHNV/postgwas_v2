# Small helpers
# ======================================================================
def _clean(value: Any) -> str:
    """Config value as a clean string; '' when the value means 'not set'."""
    if value is None:
        return ""
    if isinstance(value, float):
        # pandas turns an empty CSV cell into float('nan')
        if value != value:
            return ""
        return str(value)
    text = str(value).strip()
    if text.upper() in MISSING_TOKENS:
        return ""
    return text


def _is_set(value: Any) -> bool:
    return _clean(value) != ""


def _looks_like_path(value: str) -> bool:
    """True when a value is meant to be a filesystem path.

    ``eaffile`` may legitimately be a *resource name* ('EUR') that
    ``resolve_resource_file`` resolves against the resource folder, so a bare
    name must not be reported as a missing file.
    """
    if not value:
        return False
    if os.sep in value or value.startswith("~") or "/" in value:
        return True
    lowered = value.lower()
    return any(lowered.endswith(suffix) for suffix in _PATH_SUFFIXES)


def _resolve_policies(policies, problems: List[Problem]):
    """Accept a Policies object, a raw mapping, or None."""
    if policies is None:
        return default_policies()
    if isinstance(policies, Policies):
        return policies
    try:
        return load_policies(policies)
    except PolicyError as exc:
        for bad in exc.problems:
            problems.append(
                Problem(
                    config_key=bad.key,
                    configured_value=bad.value,
                    issue=bad.message,
                    suggestion="Correct the value in the policies block.",
                    category="policy",
                    stage="config",
                )
            )
        return default_policies()


def _ok(problems: Sequence[Problem]) -> bool:
    return not any(p.severity == "error" for p in problems)


def _severity_for(action: str) -> str:
    """'fail' -> error, anything else ('warn') -> warning."""
    return "error" if str(action).lower() == "fail" else "warning"


_emit = emit_message


