# ======================================================================
# The record every message is generated from
# ======================================================================
@dataclass(frozen=True)
class Problem(object):
    """One thing that is wrong, described well enough to be fixed.

    ``config_key``       the config entry at fault (or a comma-joined list of
                         them, for problems that involve more than one).
    ``configured_value`` what the config said.  ``None`` renders the issue as a
                         complete sentence instead of ``key = value  issue``.
    ``issue``            what is wrong with it, in plain English.
    ``suggestion``       what to do about it.
    """

    config_key: str
    configured_value: Any
    issue: str
    suggestion: str = ""
    category: str = "bad_value"
    stage: str = ""
    severity: str = "error"
    #: when the issue is already a complete sentence naming the keys itself,
    #: render it on its own instead of prefixing the key again.
    standalone: bool = False

    # -- rendering ----------------------------------------------------
    def rendered_value(self) -> str:
        if self.configured_value is None:
            return ""
        return "'%s'" % (self.configured_value,)

    def line(self, key_width: int = 0, value_width: int = 0) -> str:
        issue = self.issue.rstrip().rstrip(".")
        if self.standalone:
            text = "%s." % (issue,)
        elif self.configured_value is None:
            text = "%s : %s." % (self.config_key.ljust(key_width), issue)
        else:
            text = "%s = %s %s." % (
                self.config_key.ljust(key_width),
                self.rendered_value().ljust(value_width),
                issue,
            )
        if self.suggestion:
            text = "%s  %s" % (text, self.suggestion)
        return text.rstrip()

    def __str__(self) -> str:
        return self.line()


class ConfigError(Exception):
    """Raised instead of ``sys.exit(1)`` so a caller can catch it (plan 2.5).

    ``SystemExit`` derives from ``BaseException``, so ``except Exception`` in
    ``cli.py`` never sees it and one bad dataset kills the whole batch.
    """

    def __init__(self, problems, message: Optional[str] = None):
        self.problems = list(problems or [])
        if message is None:
            message = format_problems(self.problems)
        super(ConfigError, self).__init__(message)


