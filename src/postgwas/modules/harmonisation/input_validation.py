# STAGE 3 — needs the parsed data
# ======================================================================
def validate_content(cfg, df, policies=None, logger=None):
    # type: (Dict[str, Any], pl.DataFrame, Any, Any) -> Tuple[bool, List[Problem]]
    """Stage 3 — the checks that only the parsed frame can answer.

    A configured column that exists but is entirely null; a numeric column that
    arrived as text because one cell would not parse; and zero variants
    surviving the basic coordinate and allele checks.
    """
    problems = []  # type: List[Problem]
    policies = _resolve_policies(policies, problems)
    cfg = cfg or {}

    if df is None:
        problems.append(
            Problem(
                config_key="sumstat_file",
                configured_value=None,
                issue="no data frame was produced by the read",
                suggestion="The read step failed before content could be checked.",
                category="no_variants",
                stage="content",
            )
        )
        return False, problems

    if df.height == 0:
        problems.append(
            Problem(
                config_key="sumstat_file",
                configured_value=_clean(cfg.get("sumstat_file")) or None,
                issue="was read but holds no variants",
                suggestion="Check the delimiter and the '##' metadata handling.",
                category="no_variants",
                stage="content",
            )
        )
        return False, problems

    columns = set(df.columns)

    # ---- configured but entirely null -------------------------------
    checked = []
    owner = {}  # type: Dict[str, str]
    for key in COLUMN_CONFIG_KEYS:
        value = _clean(cfg.get(key))
        if value and value in columns:
            if value not in owner:
                owner[value] = key
                checked.append(value)
    if checked:
        # de-duplicated, or two identical aliases raise polars DuplicateError
        null_counts = df.select(
            [pl.col(name).null_count().alias(name) for name in checked]
        ).row(0)
        for name, nulls in zip(checked, null_counts):
            if nulls == df.height:
                problems.append(
                    Problem(
                        config_key=owner[name],
                        configured_value=name,
                        issue="is present in the file but every one of its %d values is missing"
                        % df.height,
                        suggestion="The column exists but carries no data.",
                        category="all_null",
                        stage="content",
                    )
                )

    # ---- numeric column that arrived as text ------------------------
    for key in NUMERIC_COLUMN_KEYS:
        name = _clean(cfg.get(key))
        if not name or name not in columns:
            continue
        dtype = df.schema[name]
        if dtype not in (pl.Utf8, pl.String):
            continue
        series = df.get_column(name)
        cast = series.cast(pl.Float64, strict=False)
        unparseable = cast.null_count() - series.null_count()
        if unparseable <= 0:
            continue
        examples = (
            df.lazy()
            .filter(
                pl.col(name).is_not_null()
                & pl.col(name).cast(pl.Float64, strict=False).is_null()
            )
            .select(pl.col(name).unique().head(5))
            .collect()
            .get_column(name)
            .to_list()
        )
        problems.append(
            Problem(
                config_key=key,
                configured_value=name,
                issue="must hold numbers but %d value(s) will not parse" % unparseable,
                suggestion="Unparseable values include: %s."
                % ", ".join(repr(v) for v in examples),
                category="not_numeric",
                stage="content",
            )
        )

    # ---- zero variants surviving the basic checks -------------------
    # The normal pipeline reaches this function only after the input reader
    # has normalized and filtered these fields.  Its private marker plus exact
    # canonical dtypes make that contract checkable without scanning rows.
    # Direct callers without the contract retain the complete validation.
    if has_canonical_variant_columns(df, cfg):
        if logger is not None:
            _emit(
                logger,
                "Coordinate and allele content checks reused the completed "
                "dataset-level validation; no second row scan was required.",
            )
    else:
        chr_col = _clean(cfg.get("chr_col"))
        pos_col = _clean(cfg.get("pos_col"))
        ea_col = _clean(cfg.get("ea_col"))
        oa_col = _clean(cfg.get("oa_col"))
        allowed = [str(c).upper() for c in policies.get("chromosome.allowed")]
        pattern = str(policies.get("allele.pattern"))
        min_position = int(policies.get("position.min_value"))

        mask = pl.lit(True)
        applied = []
        if chr_col in columns:
            mask = mask & (
                pl.col(chr_col)
                .cast(pl.Utf8, strict=False)
                .str.strip_chars()
                .str.replace(r"(?i)^chr", "", literal=False)
                .str.to_uppercase()
                .is_in(allowed)
            )
            applied.append("chromosome")
        if pos_col in columns:
            mask = mask & (
                pl.col(pos_col)
                .cast(pl.Float64, strict=False)
                .cast(pl.Int64, strict=False)
                >= min_position
            )
            applied.append("position")
        if ea_col in columns and oa_col in columns:
            mask = (
                mask
                & pl.col(ea_col)
                .cast(pl.Utf8, strict=False)
                .str.to_uppercase()
                .str.contains(pattern)
                & pl.col(oa_col)
                .cast(pl.Utf8, strict=False)
                .str.to_uppercase()
                .str.contains(pattern)
            )
            applied.append("alleles")
        if applied:
            surviving = int(df.select(mask.fill_null(False).sum()).item())
            if surviving == 0:
                problems.append(
                    Problem(
                        config_key="chr_col, pos_col, ea_col, oa_col",
                        configured_value=None,
                        issue="none of the %d variants pass the basic %s checks"
                        % (df.height, " / ".join(applied)),
                        suggestion=(
                            "Check chromosome.allowed, position.min_value and "
                            "allele.pattern, and that the columns are mapped correctly."
                        ),
                        category="no_variants",
                        stage="content",
                    )
                )

    valid = _ok(problems)
    if logger is not None:
        if valid:
            _emit(
                logger,
                "Content check passed on %d variants." % df.height,
            )
        else:
            _emit(logger, format_problems(problems, title="Content check"), warn=True)
    return valid, problems


