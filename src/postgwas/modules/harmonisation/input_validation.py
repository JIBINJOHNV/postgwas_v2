# STAGE 1 — config only, nothing is read from the summary statistics
# ======================================================================
def _check_file(
    key: str,
    value: str,
    human: str,
    problems: List[Problem],
    required: bool,
) -> None:
    if key in ("eaffile", "infofile"):
        try:
            validate_external_resource_spec(value)
        except ValueError as exc:
            problems.append(
                Problem(
                    config_key=key,
                    configured_value=value,
                    issue=str(exc),
                    suggestion=(
                        "Use one existing file for all chromosomes or an explicit "
                        "path template containing {chromosome}."
                    ),
                    category="file_missing",
                    stage="config",
                )
            )
        return
    if not os.path.exists(value):
        problems.append(
            Problem(
                config_key=key,
                configured_value=value,
                issue="does not exist",
                suggestion="Check the path to %s.%s"
                % (human, " This file is mandatory." if required else ""),
                category="file_missing",
                stage="config",
            )
        )
        return
    try:
        empty = os.path.isfile(value) and os.path.getsize(value) == 0
    except OSError as exc:
        problems.append(
            Problem(
                config_key=key,
                configured_value=value,
                issue="could not be inspected (%s)" % exc,
                suggestion="Check permissions on %s." % human,
                category="file_missing",
                stage="config",
            )
        )
        return
    if empty:
        problems.append(
            Problem(
                config_key=key,
                configured_value=value,
                issue="is empty",
                suggestion="%s has zero bytes." % human.capitalize(),
                category="file_missing",
                stage="config",
            )
        )
        return
    if not os.access(value, os.R_OK):
        problems.append(
            Problem(
                config_key=key,
                configured_value=value,
                issue="cannot be read",
                suggestion="Check the permissions on %s." % human,
                category="file_missing",
                stage="config",
            )
        )
        return
    # A directory passes exists() and getsize(), so it has to be excluded
    # explicitly or it fails much later with IsADirectoryError.
    if not os.path.isfile(value):
        problems.append(
            Problem(
                config_key=key,
                configured_value=value,
                issue="is a directory, not a file",
                suggestion="Point %s at the file itself." % key,
                category="file_missing",
                stage="config",
            )
        )
        return
    # Opening a compressed file proves it is actually readable as what its
    # extension claims.  A truncated or half-copied .gz otherwise gets through
    # here and fails part-way through the parse, long after the run started.
    message = _first_bytes_readable(value)
    if message:
        problems.append(
            Problem(
                config_key=key,
                configured_value=value,
                issue=message,
                suggestion=(
                    "%s could not be opened for reading. If it was copied or "
                    "downloaded, check the transfer completed." % human.capitalize()
                ),
                category="file_unreadable",
                stage="config",
            )
        )


def _first_bytes_readable(path):
    """Try to read the first line, honouring the compression the name implies.

    Returns None when fine, or a short description of what went wrong.  Only the
    first block is touched, so this stays cheap on a ten-million-row file.
    """
    lowered = str(path).lower()
    try:
        if lowered.endswith((".gz", ".bgz")):
            import gzip
            with gzip.open(path, "rb") as handle:
                handle.read(4096)
        elif lowered.endswith((".xz", ".lzma")):
            import lzma
            with lzma.open(path, "rb") as handle:
                handle.read(4096)
        elif lowered.endswith(".bz2"):
            import bz2
            with bz2.open(path, "rb") as handle:
                handle.read(4096)
        elif lowered.endswith(".zip"):
            import zipfile
            with zipfile.ZipFile(path) as archive:
                names = archive.namelist()
                if not names:
                    return "is an empty zip archive"
                with archive.open(names[0]) as handle:
                    handle.read(4096)
        else:
            with open(path, "rb") as handle:
                handle.read(4096)
    except Exception as exc:                       # noqa: BLE001 - reported, not raised
        return "could not be read (%s: %s)" % (type(exc).__name__, exc)
    return None


def _check_external_column(
    file_key: str,
    column_key: str,
    cfg: Dict[str, Any],
    policies,
    problems: List[Problem],
) -> None:
    """An external file must actually contain the column it is asked to supply."""
    path = _clean(cfg.get(file_key))
    column = _clean(cfg.get(column_key))
    if not path or not column:
        return
    if not _looks_like_path(path):
        return
    try:
        matches = matching_external_resource_files(path)
    except ValueError:
        return
    if not matches:
        return
    inspected_path = str(matches[0])
    try:
        header, _sep = read_summary_statistics_header(inspected_path, policies)
    except Exception as exc:
        problems.append(
            Problem(
                config_key=file_key,
                configured_value=inspected_path,
                issue="header could not be read (%s)" % exc,
                suggestion="The file may be corrupt or use an unexpected format.",
                category="file_missing",
                stage="config",
            )
        )
        return
    if not header or column in header:
        return
    cutoff = float(policies.get("validation.fuzzy_match_cutoff"))
    close = difflib.get_close_matches(column, header, n=1, cutoff=cutoff)
    suggestion = (
        "Closest match in that file: '%s'." % close[0]
        if close
        else "Columns in that file: %s." % ", ".join(header[:12])
    )
    problems.append(
        Problem(
            config_key=column_key,
            configured_value=column,
            issue="is not a column of %s" % os.path.basename(path),
            suggestion=suggestion,
            category="external_column_missing",
            stage="config",
        )
    )


def _positive_int(
    key: str, value: Any, minimum: int, problems: List[Problem]
) -> None:
    text = _clean(value)
    if not text:
        return
    try:
        number = float(text)
    except (TypeError, ValueError):
        problems.append(
            Problem(
                config_key=key,
                configured_value=text,
                issue="is not a number",
                suggestion="Sample sizes must be whole numbers.",
                category="bad_value",
                stage="config",
            )
        )
        return
    if number != int(number):
        problems.append(
            Problem(
                config_key=key,
                configured_value=text,
                issue="is not a whole number",
                suggestion="Sample sizes must be whole numbers.",
                category="bad_value",
                stage="config",
            )
        )
        return
    if int(number) < minimum:
        problems.append(
            Problem(
                config_key=key,
                configured_value=text,
                issue="is below the smallest accepted sample size (%d)" % minimum,
                suggestion="See policy sample_size.min_value.",
                category="bad_value",
                stage="config",
            )
        )


def _first_existing(cfg: Dict[str, Any], *keys: str) -> str:
    for key in keys:
        value = _clean(cfg.get(key))
        if value:
            return value
    return ""


